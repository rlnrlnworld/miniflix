const SUFFIX_MAX = 999;

function pick<T>(list: readonly T[]): T {
  return list[Math.floor(Math.random() * list.length)];
}

export function randomNickname(withSuffix = false): string {
  const base = `${pick(ADJECTIVES)} ${pick(ANIMALS)}`;
  if (!withSuffix) return base;
  return `${base} ${Math.floor(Math.random() * SUFFIX_MAX) + 1}`;
}

